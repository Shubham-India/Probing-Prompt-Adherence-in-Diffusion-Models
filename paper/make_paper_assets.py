"""Figures and number macros for the manuscript, generated ONLY from verified, committed evidence and read-only imports of the frozen code.
Sources: docs/evidence/dev_analysis_20261020/dev_constants_final.json (corrected DEV analysis, w_lo from the HPS guard), docs/evidence/audit_20261019/
audit_verdicts.json, docs/evidence/hps_guard_20261020/hps_guard.json, protocol/protocol_freeze.json (frozen constants, TEST manifest hashes) and
src/manifests.py + src/cag.py (job counts and the exact guidance schedules of the frozen design).
Writes: paper/tables/r3_numbers.tex (\newcommand macros), paper/tables/r3_design.tex, paper/tables/related_comparison.tex is hand-written (not here);
figures: paper/figures/fig_concept.pdf (CONCEPTUAL), fig_cag_schedules.pdf (exact schedules of the frozen design), fig_dev_curves.pdf,
fig_hps_guard.pdf, fig_audit.pdf (EMPIRICAL, DEV).
Usage: python paper/make_paper_assets.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
EV = ROOT / "docs" / "evidence"
FIG, TAB = ROOT / "paper" / "figures", ROOT / "paper" / "tables"
KIND = {"presence": "presence", "count": "count", "bind_given_pres": "binding | presence", "spatial_given_pres": "spatial | presence", "joint_bind": "joint binding"}


def macros(d):
    lines = ["% generated by paper/make_paper_assets.py from verified evidence - do not edit"]
    for k, v in sorted(d.items()):
        lines.append(rf"\newcommand{{\{k}}}{{{v}}}")
    (TAB / "r3_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "axes.spines.top": False, "axes.spines.right": False, "pdf.fonttype": 42})
    dc = json.loads((EV / "dev_analysis_20261020" / "dev_constants_final.json").read_text())
    au = json.loads((EV / "audit_20261019" / "audit_verdicts.json").read_text())
    hp = json.loads((EV / "hps_guard_20261020" / "hps_guard.json").read_text())
    fz = json.loads((ROOT / "protocol" / "protocol_freeze.json").read_text())
    import manifests as M
    import cag as CAG
    jobs, _, _ = M.build(constants=fz["constants"])
    cnt = {st: [j for j in jobs if j["stage"] == st] for st in M.STAGES}
    eq = {st: sum(j["unet_calls"] for j in v) / 80 for st, v in cnt.items()}
    g, ha, c = dc["gates"], dc["ha_dev"]["variants"], dc["constants"]
    t50 = c["t50_dev_w7.5"]
    N = dict(devCoreJobs=f"{len(cnt['DEV_CORE']):,}", devCommitJobs=f"{len(cnt['DEV_COMMIT']):,}", devCagJobs=f"{len(cnt['DEV_CAG_GUARD']):,}",
             testCoreJobs=f"{len(cnt['TEST_CORE']):,}", testCommitJobs=f"{len(cnt['TEST_COMMIT']):,}", testCagJobs=f"{len(cnt['TEST_CAG_SIZE']):,}",
             testEq=f"{sum(eq[s] for s in ('TEST_CORE', 'TEST_COMMIT', 'TEST_CAG_SIZE')):,.0f}",
             haHalfwidth=f"{g['HA_dev_halfwidth_le_4']['value']:.2f}", fullMaxC=f"{g['full_resample_control_max_abs_C_le_0.15']['value']:.3f}",
             hdPresTwo=str(g["HD_presence_gate_w2"]["value"]), hdPresFifteen=str(g["HD_presence_gate_w15"]["value"]),
             devScenesHA=str(ha["D8"]["n_scenes"]),
             tPres=f"{t50['presence']:.2f}", tCount=f"{t50['count']:.2f}", tBind=f"{t50['bind_given_pres']:.1f}", tSpat=f"{t50['spatial_given_pres']:.1f}",
             tJoint=f"{t50['joint_bind']:.1f}", sStarGlobal=str(c["s_star_global"]), wLo=f"{c['w_lo']:g}",
             dtDeight=f"{ha['D8']['delta_t50']['estimate']:.2f}", dtDeightLo=f"{ha['D8']['delta_t50']['ci95'][0]:.2f}", dtDeightHi=f"{ha['D8']['delta_t50']['ci95'][1]:.2f}",
             dtErThirty=f"{ha['ER30']['delta_t50']['estimate']:.2f}", dtErThirtyLo=f"{ha['ER30']['delta_t50']['ci95'][0]:.2f}", dtErThirtyHi=f"{ha['ER30']['delta_t50']['ci95'][1]:.2f}",
             hpsOne=f"{hp['per_w_lo']['1']['mean_change_points']:.3f}", hpsOneLo=f"{hp['per_w_lo']['1']['ci95_points'][0]:.3f}", hpsOneHi=f"{hp['per_w_lo']['1']['ci95_points'][1]:.3f}",
             hpsThree=f"{hp['per_w_lo']['3']['mean_change_points']:.3f}", hpsThreeLo=f"{hp['per_w_lo']['3']['ci95_points'][0]:.3f}", hpsThreeHi=f"{hp['per_w_lo']['3']['ci95_points'][1]:.3f}",
             hpsPairs=str(hp["per_w_lo"]["1"]["n_pairs"]),
             accPres=f"{au['presence']['weighted_accuracy']:.3f}", accCount=f"{au['count']['weighted_accuracy']:.3f}", accBind=f"{au['binding']['weighted_accuracy']:.3f}",
             accSpat=f"{au['spatial']['weighted_accuracy']:.3f}", accSize=f"{au['size']['weighted_accuracy']:.3f}",
             freezeCommit=str(fz.get("approved_utc", ""))[:10], frozenFiles=str(len(fz["files"])))
    macros(N)

    stages = [("DEV", "DEV_CORE", "variants, CF bases, DEV size family"), ("DEV", "DEV_COMMIT", "restarts D8/ER30/FULL, CFG 2/15 bases and restarts, switches"),
              ("DEV", "DEV_CAG_GUARD", r"CAG $w_{lo}\in\{1,3\}$ quality guard"), ("TEST", "TEST_CORE", r"all variants; CFG $\times$ steps"),
              ("TEST", "TEST_COMMIT", "restarts at CFG 2/7.5/15; prompt switches"), ("TEST", "TEST_CAG_SIZE", "CAG arms A2/A3/A4/A6; size family with restarts and switches")]
    L = [r"\begin{table}[t]\centering\small", r"\caption{Frozen stage manifests (job counts and full-generation equivalents from \texttt{src/manifests.py} with the frozen constants).}\label{tab:design}",
         r"\begin{tabular}{llp{6.3cm}rr}", r"\toprule", r"Split & Stage & Content & Jobs & Equiv. \\", r"\midrule"]
    L += [rf"{sp} & {st.replace('_', chr(92) + '_')} & {txt} & {len(cnt[st]):,} & {eq[st]:,.0f} \\" for sp, st, txt in stages]
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (TAB / "r3_design.tex").write_text("\n".join(L) + "\n", encoding="utf-8")

    # CONCEPTUAL: the two probes and CAG on the 40-step DDIM trajectory
    fig, ax = plt.subplots(figsize=(6.6, 2.3))
    ax.set_xlim(-1, 41); ax.set_ylim(-0.2, 3.4); ax.axis("off")
    ax.annotate("", xy=(40, 2.6), xytext=(0, 2.6), arrowprops=dict(arrowstyle="->", lw=1.2))
    ax.text(0, 2.85, "noise", ha="left"); ax.text(40, 2.85, "image", ha="right"); ax.text(20, 3.15, "base trajectory (DDIM, 40 steps, CFG w)", ha="center")
    for t in (6, 12, 18, 24, 30, 36):
        ax.plot([t], [2.6], "o", ms=4, color="k")
    ax.text(1, 2.3, "saved states t = 6, 12, ..., 36", ha="left", fontsize=7)
    ax.annotate("", xy=(40, 1.6), xytext=(16, 1.6), arrowprops=dict(arrowstyle="->", lw=1, color="C0"))
    ax.plot([24, 16], [2.6, 1.6], color="C0", ls="--", lw=1)
    ax.text(0.5, 1.05, "restart probe (example t = 24): re-noise x_24 back to step 16 with fresh noise and re-denoise;\nagreement of branch and base outcomes, corrected for chance, gives C(t) and t50", fontsize=7, color="C0")
    ax.fill_between([0, 12], 0.15, 0.55, color="C3", alpha=0.35); ax.fill_between([12, 40], 0.15, 0.35, color="C2", alpha=0.35)
    ax.text(6, 0.65, "w_hi = 7.5", ha="center", fontsize=7); ax.text(26, 0.45, "w_lo (after s*)", ha="center", fontsize=7)
    ax.text(0, -0.15, "CAG: s* = ceil(max t50_DEV of the prompt's constraint types) + 2", fontsize=7)
    fig.tight_layout(); fig.savefig(FIG / "fig_concept.pdf"); fig.savefig(ROOT / "local_audit" / "fig_concept_preview.png", dpi=110); plt.close(fig)

    # EXACT schedules of the frozen design for the two switch steps that occur on TEST (s* = 12, 21)
    w_hi, w_lo, n = 7.5, fz["constants"]["w_lo"], 40
    fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.2), sharey=True)
    for ax, s in zip(axes, (12, 21)):
        sch, mean = CAG.schedules(s, w_hi, w_lo, n)
        sch["A1"] = [w_hi] * n                       # constant CFG 7.5 (the core images)
        for arm, ls in (("A1", "-"), ("A2", "-"), ("A4", "--"), ("A6", ":")):
            if sch.get(arm) is not None:
                ax.step(range(n), sch[arm], where="post", ls=ls, label=arm)
        ax.set_title(f"s* = {s}", fontsize=8); ax.set_xlabel("denoising step")
    axes[0].set_ylabel("guidance w"); axes[1].legend(fontsize=7, frameon=False)
    fig.tight_layout(); fig.savefig(FIG / "fig_cag_schedules.pdf"); plt.close(fig)

    # EMPIRICAL DEV persistence curves (corrected estimator)
    grid = [6, 12, 18, 24, 30, 36]
    fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.5), sharey=True)
    for ax, v in zip(axes, ("D8", "ER30")):
        for k, cur in ha[v]["curves"].items():
            ax.plot(grid, [float("nan") if x is None else x for x in cur], marker="o", ms=3, label=KIND.get(k, k))
        ax.axhline(0.5, color="grey", lw=0.7, ls="--"); ax.set_title(f"DEV, {v}, w = 7.5", fontsize=8); ax.set_xlabel("restart step t")
    axes[0].set_ylabel("persistence C(t)"); axes[1].legend(fontsize=6, frameon=False)
    fig.tight_layout(); fig.savefig(FIG / "fig_dev_curves.pdf"); plt.close(fig)

    # EMPIRICAL HPS guard
    fig, ax = plt.subplots(figsize=(3.0, 2.2))
    for i, w in enumerate(("1", "3")):
        r = hp["per_w_lo"][w]
        ax.errorbar([i], [r["mean_change_points"]], yerr=[[r["mean_change_points"] - r["ci95_points"][0]], [r["ci95_points"][1] - r["mean_change_points"]]], fmt="o", capsize=3)
    ax.axhline(-0.5, color="red", ls=":", lw=0.8); ax.axhline(0, color="grey", lw=0.6)
    ax.set_xticks([0, 1]); ax.set_xticklabels(["w_lo = 1", "w_lo = 3"]); ax.set_ylabel("HPS change vs A1 (points)")
    fig.tight_layout(); fig.savefig(FIG / "fig_hps_guard.pdf"); plt.close(fig)

    # EMPIRICAL audit
    types = ["presence", "count", "binding", "spatial", "size"]
    fig, ax = plt.subplots(figsize=(3.4, 2.2))
    for i, t in enumerate(types):
        r = au[t]
        ax.errorbar([i], [r["weighted_accuracy"]], yerr=[[r["weighted_accuracy"] - r["ci95"][0]], [r["ci95"][1] - r["weighted_accuracy"]]], fmt="o", capsize=3,
                    color="C2" if r["criterion_met"] else "C3")
    ax.axhline(0.85, color="grey", ls="--", lw=0.8); ax.set_xticks(range(5)); ax.set_xticklabels(types, rotation=20); ax.set_ylabel("weighted accuracy"); ax.set_ylim(0.45, 1.0)
    fig.tight_layout(); fig.savefig(FIG / "fig_audit.pdf"); plt.close(fig)
    rows = [f"{t} & {au[t]['n_used']} & {au[t]['weighted_accuracy']:.3f} & [{au[t]['ci95'][0]:.3f}, {au[t]['ci95'][1]:.3f}] & {'yes' if au[t]['criterion_met'] else 'no'} \\\\" for t in types]
    (ROOT / "paper" / "tables" / "dev_audit.tex").write_text("\n".join([
        "% generated by paper/make_paper_assets.py from docs/evidence/audit_20261019/audit_verdicts.json", r"\begin{table}[t]", r"\centering\small",
        r"\caption{DEV evaluator audit of J1 against blinded human labels (one annotator; population-weighted accuracy, stratified bootstrap 95\% CI). Only types meeting $\geq 0.85$ may carry a confirmatory claim.}",
        r"\label{tab:dev-audit}", r"\begin{tabular}{lrrrr}", r"\toprule", r"Type & $n$ & Accuracy & 95\% CI & $\geq 0.85$ \\", r"\midrule", *rows,
        r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]), encoding="utf-8")
    print("wrote", sorted(p.name for p in FIG.glob("fig_*.pdf")), "and tables/r3_numbers.tex, tables/r3_design.tex")


if __name__ == "__main__":
    main()
