"""Builds report/presentation.pptx and report/speaker_notes.md from saved figures and result files.

Every number in the slides and notes is filled from src/report_numbers.py (no hand-typed results).
Usage: python report/make_slides.py   (after python src/figures.py ... and python report/build_report.py)
"""
import math
import sys
from importlib.metadata import version
from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from pptx.util import Emu, Inches, Pt

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "report"))
from build_report import split_sections  # noqa: E402
from report_numbers import numbers  # noqa: E402

FIG = ROOT / "outputs" / "main" / "figures"
INT_FIG = ROOT / "outputs" / "main" / "figures" / "intervention.png"
NAVY, ORANGE, GREY = RGBColor(0x1F, 0x3A, 0x5F), RGBColor(0xF5, 0x85, 0x18), RGBColor(0x33, 0x33, 0x33)
W, H = Inches(13.33), Inches(7.5)
FMT = {}  # numbers for the slide text, filled in build()


def add_text(slide, left, top, width, height, paragraphs, size=20, color=GREY, bold=False, bullet=True, min_size=13):
    """Adds a text box and shrinks the font until the estimated wrapped height fits the box."""
    paragraphs = [p.format_map(FMT) for p in paragraphs]
    width_in, height_in = width / 914400, height / 914400

    def needed(sz):
        chars_per_line = max(10, int(width_in * 72 / (sz * 0.50)))
        lines = sum(max(1, math.ceil((len(p) + 2) / chars_per_line)) for p in paragraphs)
        return (lines * sz * 1.22 + len(paragraphs) * 9) / 72

    while size > min_size and needed(size) > height_in:
        size -= 1
    box = slide.shapes.add_textbox(left, top, width, height).text_frame
    box.word_wrap = True
    for i, text in enumerate(paragraphs):
        p = box.paragraphs[0] if i == 0 else box.add_paragraph()
        p.text = ("• " if bullet else "") + text
        p.font.size, p.font.bold, p.font.color.rgb = Pt(size), bold, color
        p.space_after = Pt(9)
    return size


def new_slide(prs, title, number):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_text(slide, Inches(0.6), Inches(0.3), Inches(12.1), Inches(0.9), [title], size=30, color=NAVY, bold=True, bullet=False)
    bar = slide.shapes.add_shape(1, Inches(0.6), Inches(1.15), Inches(12.1), Inches(0.05))
    bar.fill.solid()
    bar.fill.fore_color.rgb = ORANGE
    bar.line.fill.background()
    add_text(slide, Inches(0.6), Inches(7.05), Inches(10), Inches(0.35), ["Where Does the Prompt Go?  |  Stable Diffusion 1.5 prompt-adherence study"], size=11, color=RGBColor(0x88, 0x88, 0x88), bullet=False)
    add_text(slide, Inches(12.0), Inches(7.05), Inches(0.8), Inches(0.35), [str(number)], size=11, color=RGBColor(0x88, 0x88, 0x88), bullet=False)
    return slide


def add_picture(slide, path, left, top, max_w, max_h):
    """Places the picture as large as the box allows, centred, aspect ratio preserved."""
    pic = slide.shapes.add_picture(str(path), left, top)
    ratio = min(max_w / pic.width, max_h / pic.height)
    pic.width, pic.height = int(pic.width * ratio), int(pic.height * ratio)
    pic.left, pic.top = int(left + (max_w - pic.width) / 2), int(top + (max_h - pic.height) / 2)
    return pic


def add_table(slide, rows, left, top, width, col_widths, font=14):
    shape = slide.shapes.add_table(len(rows), len(rows[0]), left, top, width, Inches(0.42 * len(rows)))
    for j, w in enumerate(col_widths):
        shape.table.columns[j].width = int(width * w)
    for i, row in enumerate(rows):
        for j, text in enumerate(row):
            cell = shape.table.cell(i, j)
            cell.text = str(text)
            for p in cell.text_frame.paragraphs:
                p.font.size = Pt(font)
                p.font.bold = i == 0
                p.alignment = PP_ALIGN.LEFT if j == 0 else PP_ALIGN.CENTER


def build():
    V = numbers(ROOT / "outputs" / "main")
    V.update(diffusers_version=version("diffusers"))
    for key, text in split_sections((ROOT / "report" / "intervention_template.md").read_text(encoding="utf-8")).items():
        V["INT_" + key] = text.format_map(V)
    FMT.update(V)
    prs = Presentation()
    prs.slide_width, prs.slide_height = W, H
    notes_md = ["# Speaker notes (generated by report/make_slides.py)\n"]

    def finish(slide, i, title, notes):
        notes = notes.format_map(V)
        slide.notes_slide.notes_text_frame.text = notes
        notes_md.append(f"## Slide {i}: {title}\n\n{notes}\n")

    # 1 ---------------------------------------------------------------
    t = "Where Does the Prompt Go?"
    s = new_slide(prs, t, 1)
    add_text(s, Inches(0.6), Inches(1.5), Inches(12.1), Inches(1.0), ["Probing prompt adherence in Stable Diffusion 1.5: guidance, denoising steps, cross-attention and a simple fix"], size=24, bullet=False)
    add_text(s, Inches(0.6), Inches(2.8), Inches(12.1), Inches(3.9), [
        "{n_images} images: {n_prompts} controlled prompts x 3 CFG scales x 2 step counts x {n_seeds} seeds, all paired",
        "{n_attention} cross-attention extractions; {int_n_images} images in a matched intervention test",
        "Measured adherence rises only weakly with guidance ({cfg72_all_diff} from CFG 2 to 7.5, CI {cfg72_all_ci}); similarity and diversity change clearly",
        "{INT_SLIDE_HEADLINE}"], size=22)
    finish(s, 1, t, "A diffusion model can draw a convincing picture and still ignore part of the prompt: wrong colours, a missing object, the wrong count. "
           "I asked how guidance scale and denoising steps change that for five kinds of constraint, whether cross-attention shows the failure, and whether a cheap inference-time change helps. "
           "I will show the measurements, including what stayed inconclusive.")

    # 2 ---------------------------------------------------------------
    t = "Hypotheses, written before the main run"
    s = new_slide(prs, t, 2)
    add_text(s, Inches(0.6), Inches(1.5), Inches(12.1), Inches(5.3), [
        "H1  CFG 2 -> 7.5 improves every constraint type; 7.5 -> 15 adds little for binding, counting and multi-constraint prompts",
        "H2  20 vs 40 denoising steps matters much less than CFG, with no CFG x steps interaction",
        "H3  (exploratory) Higher CFG localises object attention; colour tokens overlap the wrong object in binding failures; attention alone is a weak predictor (AUC < 0.75)",
        "H4  (added before the intervention run) Boosting object and colour token attention by 2x at CFG 7.5 raises success by >= 0.05 without hurting CLIP score by more than 0.5",
        "Refutation criteria and the analysis plan were fixed in report/protocol.md; revisions are logged there"], size=22)
    finish(s, 2, t, "CFG pushes the noise prediction away from the unconditional one: eps = eps_uncond + w (eps_cond - eps_uncond). I predicted a rise up to the default and a plateau beyond it, a small effect of steps, "
           "and more localised object attention with guidance. H4 was added after the main results, before any intervention image was generated: scale the attention weight of the object and colour words, a gradient-free cousin of Prompt-to-Prompt re-weighting. "
           "For each prediction I wrote down what would contradict it.")

    # 3 ---------------------------------------------------------------
    t = "Method"
    s = new_slide(prs, t, 3)
    add_picture(s, FIG / "methodology.png", Inches(0.6), Inches(1.4), Inches(12.1), Inches(3.3))
    add_text(s, Inches(0.6), Inches(4.85), Inches(12.1), Inches(2.1), [
        "Same seed gives the same noise in every CFG x steps cell, so every contrast is paired by prompt and seed",
        "Statistics treat the prompt as the unit: cluster bootstrap CIs, Wilcoxon on prompt-level differences, Holm correction",
        "The attention hook leaves images bit-identical (max pixel difference 0), so the maps describe the images that were scored"], size=19)
    finish(s, 3, t, "Prompts come from templates with structured constraints, so evaluation never parses text. Generation and evaluation are separate programs. "
           "The attention hook computes the output with the default fused kernel and only recomputes the probabilities for recording, which is why the images are bit-identical. "
           "Because seeds repeat across all cells, I compare the same prompt and seed under different settings, and I resample prompts, not images, for uncertainty.")

    # 4 ---------------------------------------------------------------
    t = "Benchmark and metrics"
    s = new_slide(prs, t, 4)
    add_text(s, Inches(0.6), Inches(1.5), Inches(6.4), Inches(5.4), [
        "{n_prompts} prompts: presence {nprompts_presence}, binding {nprompts_binding}, counting {nprompts_counting}, spatial {nprompts_spatial}, multi {nprompts_multi}; colour and left/right swapped variants",
        "Complexity = number of constraints (2 to 5)",
        "OWL-ViT boxes -> presence, count, left/right; CLIP colour on the object's box -> binding",
        "Primary outcome: all constraints satisfied (counting prompts: count only)",
        "Secondary: CLIP image-text score, seed diversity",
        "Labels: drafted by Claude, second pass, revised by the owner; spatial has few positives"], size=19)
    rows = [["constraint", "accuracy", "positives"]] + [
        [name, V[f"val_{key}_acc"], V[f"val_{key}_pos"]]
        for name, key in (("presence", "presence"), ("colour binding", "binding"), ("count", "count"), ("spatial", "spatial"))]
    add_text(s, Inches(7.3), Inches(1.5), Inches(5.4), Inches(0.5), ["Evaluator vs 40 hand-labelled images"], size=16, bold=True, bullet=False, color=NAVY)
    add_table(s, rows, Inches(7.3), Inches(2.1), Inches(5.4), [0.5, 0.25, 0.25])
    finish(s, 4, t, "Binding is scored by classifying the colour of the box of each object, so detecting something red and something blue is not enough: the colour must sit on the right object. "
           "The validation labels were drafted by Claude from the images, adjusted in a second pass, and then revised by me; ambiguous constraints are set aside. "
           "Yellow-green apples are read as green by CLIP, so counting prompts are judged on the count alone. Spatial accuracy rests on very few positive examples.")

    # 5 ---------------------------------------------------------------
    t = "Adherence vs CFG and denoising steps"
    s = new_slide(prs, t, 5)
    add_picture(s, FIG / "slide_adherence.png", Inches(0.6), Inches(1.35), Inches(12.1), Inches(4.75))
    add_text(s, Inches(0.6), Inches(6.15), Inches(12.1), Inches(0.9), [
        "CFG 7.5 vs 2: {cfg72_all_diff} {cfg72_all_ci}, Holm p = {cfg72_all_holm};  CFG 15 vs 7.5: {cfg157_all_diff};  40 vs 20 steps: {steps_all_diff} {steps_all_ci};  interaction p = {gee_inter_p}"], size=15, bullet=False)
    finish(s, 5, t, "Overall success is low, {cell_min_all} to {cell_max_all} depending on the cell. Going from CFG 2 to 7.5 raises overall success by {cfg72_all_diff}, interval {cfg72_all_ci}: positive but not significant. "
           "From 7.5 to 15 there is no gain overall, and spatial prompts fall at CFG 15 with 40 steps. Steps change little and there is no CFG by steps interaction. "
           "With four to six prompts per category the per-category tests have little power, so I report intervals and do not claim category effects. CLIP similarity rises by {clip72_diff} and diversity falls from {div_2} to {div_7p5}: guidance clearly changes the images even if measured adherence barely moves.")

    # 6 ---------------------------------------------------------------
    t = "What success and failure look like"
    s = new_slide(prs, t, 6)
    add_picture(s, FIG / "slide_contact_sheet.png", Inches(0.8), Inches(1.3), Inches(5.0), Inches(5.7))
    add_text(s, Inches(6.4), Inches(1.5), Inches(6.4), Inches(5.4), [
        "Rule: per category, the prompt closest to the median success rate; seed 0; 40 steps (all six settings: contact_sheet.png); green = success, red = failure",
        "CFG 2: washed-out images, objects often missing",
        "CFG 7.5-15: objects appear but colours leak (cube and sphere both red) or an object is dropped (chair, no vase)",
        "Spatial: the requested side is not respected at any setting"], size=18)
    finish(s, 6, t, "One prompt per category, chosen by a fixed rule so I do not show only successes, with seed 0 in all six settings. At CFG 2 images are low contrast and often miss the objects. "
           "At higher CFG the objects appear but binding fails: in the cube and sphere row both objects are red, and in the chair and vase row only a chair is drawn. That is the classic attribute-binding and neglect failure.")

    # 7 ---------------------------------------------------------------
    t = "Cross-attention of the prompt words"
    s = new_slide(prs, t, 7)
    add_picture(s, FIG / "slide_attention_maps.png", Inches(0.5), Inches(1.3), Inches(8.3), Inches(5.7))
    add_text(s, Inches(9.0), Inches(1.5), Inches(3.8), Inches(5.4), [
        "Rows: CFG 2, 7.5, 15 (same prompt and seed); columns: the words red, chair, blue, vase",
        "All four words light up the same chair: no separate region for the vase or the blue",
        "Early and late stages: attention_maps_by_cfg.png (full figure)",
        "One example chosen by rule; quantitative summary next"], size=17)
    finish(s, 7, t, "Each row is a CFG value for the same prompt and seed; the columns are the attention maps of four words in the middle of denoising. The prompt was chosen by a rule, the binding prompt closest to 50 percent success. "
           "All four word maps land on the same chair: the vase and blue tokens never get a region of their own. That is what a dropped object looks like inside the model. This is one example; the next slide is the quantitative summary.")

    # 8 ---------------------------------------------------------------
    t = "Does attention explain the outcome?"
    s = new_slide(prs, t, 8)
    add_picture(s, FIG / "slide_attention_summary.png", Inches(0.6), Inches(1.35), Inches(12.1), Inches(4.6))
    add_text(s, Inches(0.6), Inches(6.0), Inches(12.1), Inches(1.0), [
        "Localisation rises from CFG 2 to 7.5 ({att_top1072_middle} mid-stage, CI {att_top1072_middle_ci}) and does not rise at 15;  colour/object overlap margin: AUC {auc_middle_bind_margin} {auc_middle_bind_margin_ci} for binding success;  "
        "attention-only classifier AUC {clf_att} vs {clf_base} for category + CFG alone. Exploratory, correlational."], size=16, bullet=False)
    finish(s, 8, t, "Left: object-word maps become more concentrated from CFG 2 to 7.5 and do not improve at 15, parallel to the plateau in adherence. "
           "Right: the margin between how much a colour word overlaps its own object versus the other object separates binding successes from failures, with AUC {auc_middle_bind_margin}. For overall success, lower entropy goes with success, so its AUC is below 0.5. "
           "A classifier built only from attention summaries has AUC {clf_att}, no better than knowing category and CFG, {clf_base}. These are exploratory associations, not causal evidence.")

    # 9 ---------------------------------------------------------------
    t = "Simple intervention: attention re-weighting"
    s = new_slide(prs, t, 9)
    add_picture(s, INT_FIG, Inches(0.6), Inches(1.35), Inches(12.1), Inches(4.45))
    add_text(s, Inches(0.6), Inches(5.9), Inches(12.1), Inches(1.1), ["{INT_SLIDE_LINE1}", "{INT_SLIDE_LINE2}"], size=16)
    finish(s, 9, t, "{INT_NOTES}")

    # 10 --------------------------------------------------------------
    t = "Takeaways and limitations"
    s = new_slide(prs, t, 10)
    add_text(s, Inches(0.6), Inches(1.4), Inches(5.9), Inches(0.5), ["What we can say"], size=20, bold=True, color=NAVY, bullet=False)
    add_text(s, Inches(0.6), Inches(1.95), Inches(5.9), Inches(5.0), [
        "CFG 2 -> 7.5: clear gains in CLIP similarity ({clip72_diff}) and localisation, less diversity; adherence {cfg72_all_diff} (not significant)",
        "More steps or CFG 15: no measurable benefit here",
        "Binding fails by colour leakage and dropped objects; colour/object attention overlap flags it (exploratory)",
        "{INT_SLIDE_TAKEAWAY}"], size=17)
    add_text(s, Inches(6.9), Inches(1.4), Inches(5.9), Inches(0.5), ["Limitations"], size=20, bold=True, color=NAVY, bullet=False)
    add_text(s, Inches(6.9), Inches(1.95), Inches(5.9), Inches(5.0), [
        "4-6 prompts per category; different objects per category",
        "Low base rates; evaluator not perfect; one annotator; spatial barely validated",
        "One model, scheduler, resolution; coarse CFG grid",
        "Attention: conditional branch, layer/head average, correlational",
        "Intervention tested at one CFG, one step count and one token rule"], size=17)
    finish(s, 10, t, "The honest summary: guidance clearly changes similarity, diversity and attention localisation, and has a small unconfirmed effect on measured adherence. "
           "{INT_NOTES_TAKEAWAY} The study can describe associations and rule out large step effects in this range, but not confirm small per-category effects. "
           "The evaluator is imperfect, with one non-independent annotator. Natural next steps are a larger benchmark, more CFG levels, and testing re-weighting variants that target the colour/object overlap directly.")

    prs.save(ROOT / "report" / "presentation.pptx")
    (ROOT / "report" / "speaker_notes.md").write_text("\n".join(notes_md), encoding="utf-8")
    print("10 slides written")


if __name__ == "__main__":
    build()
